/*
# Activity log (audit trail) for every user

Records who did what and when, so full admins can review every user's operations in the back office.

1. New Tables
- `activity_log`
  - `id` (bigint, primary key)
  - `actor_id` (uuid, user who performed the action; kept even if the user is later deleted)
  - `actor_email` (text, email snapshot at the time of the action)
  - `action` (text, e.g. insert / update / delete / sign_in / page_view / close_position)
  - `category` (text, area of the app, e.g. accounts, copy_settings, auth, navigation)
  - `target` (text, human-readable subject, e.g. "MASTER1 -> FOLLOWER2")
  - `changes` (jsonb, for updates only the changed fields as {field: {from, to}}; full row for insert/delete)
  - `meta` (jsonb, extra details sent by the app)
  - `created_at` (timestamp)

2. Automatic recording (cannot be skipped by the browser)
- `audit_row_change()` trigger function records every insert/update/delete made by a signed-in user on:
  accounts, copy_settings, app_settings, app_members, client_accounts, copy_requests.
- Writes made by the trading terminals / copy engine (no signed-in user) are NOT recorded, to keep the log
  focused on people.
- Updates that change nothing (other than updated_at) are skipped.

3. App events
- `log_activity(p_action, p_category, p_target, p_meta)` lets a signed-in user record an event about THEMSELVES
  (actor always taken from the session). Only an allow-listed set of actions is accepted and sizes are capped.

4. Security
- RLS enabled. Only full admins can read the log.
- No insert/update/delete policies: the log is append-only and can only be written by the trigger, the
  `log_activity` function, or the server.
- Added to realtime so the admin view updates live (RLS still applies).
*/

CREATE TABLE IF NOT EXISTS activity_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id uuid,
  actor_email text,
  action text NOT NULL,
  category text NOT NULL,
  target text,
  changes jsonb,
  meta jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_activity_log_created ON activity_log (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_activity_log_actor ON activity_log (actor_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_activity_log_category ON activity_log (category, created_at DESC);

ALTER TABLE activity_log ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "admin_select_activity_log" ON activity_log;
CREATE POLICY "admin_select_activity_log" ON activity_log FOR SELECT
  TO authenticated USING (is_admin());

REVOKE INSERT, UPDATE, DELETE ON activity_log FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.audit_row_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_actor uuid := auth.uid();
  v_old jsonb;
  v_new jsonb;
  v_row jsonb;
  v_changes jsonb;
  v_target text;
BEGIN
  IF v_actor IS NULL THEN
    RETURN NULL;
  END IF;

  IF TG_OP IN ('UPDATE', 'DELETE') THEN v_old := to_jsonb(OLD); END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN v_new := to_jsonb(NEW); END IF;
  v_row := coalesce(v_new, v_old);

  IF TG_OP = 'UPDATE' THEN
    SELECT jsonb_object_agg(n.key, jsonb_build_object('from', v_old -> n.key, 'to', n.value))
      INTO v_changes
      FROM jsonb_each(v_new) n
      WHERE n.key NOT IN ('updated_at') AND (v_old -> n.key) IS DISTINCT FROM n.value;
    IF v_changes IS NULL THEN
      RETURN NULL;
    END IF;
  ELSIF TG_OP = 'INSERT' THEN
    v_changes := v_new - 'id';
  ELSE
    v_changes := v_old - 'id';
  END IF;

  v_target := CASE TG_TABLE_NAME
    WHEN 'copy_settings' THEN concat(v_row ->> 'master_account', ' -> ', v_row ->> 'follower_account')
    WHEN 'app_members' THEN v_row ->> 'email'
    WHEN 'client_accounts' THEN concat(
      (SELECT m.email FROM app_members m WHERE m.user_id = (v_row ->> 'user_id')::uuid), ' : ', v_row ->> 'account_name')
    WHEN 'copy_requests' THEN concat(v_row ->> 'email', ' -> ', v_row ->> 'master_account')
    WHEN 'app_settings' THEN 'Global settings'
    ELSE coalesce(v_row ->> 'account_name', v_row ->> 'id')
  END;

  INSERT INTO activity_log (actor_id, actor_email, action, category, target, changes)
  VALUES (
    v_actor,
    (SELECT m.email FROM app_members m WHERE m.user_id = v_actor),
    lower(TG_OP),
    TG_TABLE_NAME,
    left(v_target, 300),
    v_changes
  );
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION public.audit_row_change() FROM PUBLIC, anon, authenticated;

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['accounts', 'copy_settings', 'app_settings', 'app_members', 'client_accounts', 'copy_requests'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS audit_%1$s ON %1$I', t);
    EXECUTE format('CREATE TRIGGER audit_%1$s AFTER INSERT OR UPDATE OR DELETE ON %1$I FOR EACH ROW EXECUTE FUNCTION audit_row_change()', t);
  END LOOP;
END $$;

CREATE OR REPLACE FUNCTION public.log_activity(p_action text, p_category text, p_target text DEFAULT NULL, p_meta jsonb DEFAULT NULL)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_actor uuid := auth.uid();
BEGIN
  IF v_actor IS NULL THEN
    RAISE EXCEPTION 'Not authorized';
  END IF;
  IF p_action NOT IN ('sign_in', 'sign_out', 'sign_up', 'password_changed', 'page_view', 'view_report', 'export', 'close_position') THEN
    RAISE EXCEPTION 'Invalid action';
  END IF;
  IF p_category NOT IN ('auth', 'navigation', 'report', 'history', 'copy_requests', 'positions') THEN
    RAISE EXCEPTION 'Invalid category';
  END IF;
  IF p_meta IS NOT NULL AND length(p_meta::text) > 2000 THEN
    p_meta := NULL;
  END IF;

  INSERT INTO activity_log (actor_id, actor_email, action, category, target, meta)
  VALUES (v_actor, (SELECT m.email FROM app_members m WHERE m.user_id = v_actor), p_action, p_category, left(p_target, 300), p_meta);
END;
$$;
REVOKE ALL ON FUNCTION public.log_activity(text, text, text, jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.log_activity(text, text, text, jsonb) TO authenticated;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'activity_log'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE activity_log;
  END IF;
END $$;