/*
# Create Copy Trade Tables

1. New Tables
- `accounts`: Stores MT4/MT5 account metadata (name, broker, platform, type, balance, equity, status)
- `live_positions`: Live open positions pushed by EA every few seconds, keyed by account_name + ticket
- `trade_history`: Closed trades uploaded by EA, keyed by account_name + ticket
- `copy_settings`: Configuration for copy trading relationships (master -> follower mapping with lot mode)
- `copy_signals`: Signals generated by the copy engine for follower EAs to poll and execute

2. Relationships
- live_positions.account_name references accounts.account_name (FK)
- copy_settings.master_account references accounts.account_name (FK)
- copy_settings.follower_account references accounts.account_name (FK)

3. Security
- RLS enabled on all tables but policies allow anon + authenticated full CRUD (single-tenant, no auth — EA uses anon key)
- All policies use TO anon, authenticated with USING(true) / WITH CHECK(true) since this is intentionally shared data

4. Notes
- No user_id columns — this is a single-tenant app with no sign-in screen
- EA communicates directly via REST API using the anon key
- account_name is used as the natural key for relationships (user-defined, unique)
*/

-- ===================== ACCOUNTS =====================
CREATE TABLE IF NOT EXISTS accounts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  account_name text UNIQUE NOT NULL,
  broker text DEFAULT '',
  platform text DEFAULT 'MT4',
  type text DEFAULT 'master',
  balance float DEFAULT 0,
  equity float DEFAULT 0,
  is_active boolean DEFAULT true,
  last_seen timestamptz,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE accounts ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "anon_select_accounts" ON accounts;
CREATE POLICY "anon_select_accounts" ON accounts FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_accounts" ON accounts;
CREATE POLICY "anon_insert_accounts" ON accounts FOR INSERT
  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_accounts" ON accounts;
CREATE POLICY "anon_update_accounts" ON accounts FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_accounts" ON accounts;
CREATE POLICY "anon_delete_accounts" ON accounts FOR DELETE
  TO anon, authenticated USING (true);

